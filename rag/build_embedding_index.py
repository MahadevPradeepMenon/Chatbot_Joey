import hashlib
import json
from datetime import datetime, timezone
from importlib.metadata import version
from pathlib import Path
from typing import Any

import numpy as np
from sentence_transformers import SentenceTransformer


# Resolve chunk and index paths relative to the repository so index building
# is reproducible regardless of the current working directory.
PROJECT_ROOT = Path(__file__).resolve().parents[1]

CHUNKS_FILE = (
    PROJECT_ROOT
    / "data"
    / "processed"
    / "strategy_chunks"
    / "strategy_chunks.jsonl"
)

INDEX_DIR = PROJECT_ROOT / "data" / "indexes"

EMBEDDINGS_FILE = INDEX_DIR / "strategy_embeddings.npy"
METADATA_FILE = INDEX_DIR / "strategy_index_metadata.jsonl"
MANIFEST_FILE = INDEX_DIR / "strategy_index_manifest.json"

# Fix the embedding model, device and batch size so repeated builds use the
# same semantic representation and local CPU execution path.
MODEL_NAME = "sentence-transformers/all-MiniLM-L6-v2"
DEVICE = "cpu"
BATCH_SIZE = 32


def calculate_sha256(file_path: Path) -> str:
    """Calculate a reproducible hash for the input chunk file."""

# Hash the exact chunk file bytes in blocks so the manifest can identify the
# precise corpus used to build the index.
    sha256 = hashlib.sha256()

    with file_path.open("rb") as file:
        for block in iter(lambda: file.read(65536), b""):
            sha256.update(block)

    return sha256.hexdigest()


def load_chunks() -> list[dict[str, Any]]:
    """Load and validate the strategy chunk records."""

    # Require the chunking stage to have completed before semantic indexing begins.
    if not CHUNKS_FILE.exists():
        raise FileNotFoundError(
            f"Strategy chunk file not found: {CHUNKS_FILE}\n"
            "Run python -m rag.strategy_chunker first."
        )

    records: list[dict[str, Any]] = []

    # Read the JSONL corpus line-by-line so malformed records can be reported
    # with their exact source line number.
    with CHUNKS_FILE.open("r", encoding="utf-8") as file:
        for line_number, line in enumerate(file, start=1):
            line = line.strip()

            if not line:
                continue

            try:
                record = json.loads(line)
            except json.JSONDecodeError as error:
                raise ValueError(
                    f"Invalid JSON on line {line_number}: {error}"
                ) from error

            # Every indexed row requires both a stable chunk ID and the enriched
            # search_text generated by the chunking stage.
            chunk_id = str(record.get("chunk_id", "")).strip()
            search_text = str(record.get("search_text", "")).strip()

            if not chunk_id:
                raise ValueError(
                    f"Missing chunk_id on line {line_number}"
                )

            if not search_text:
                raise ValueError(
                    f"Missing search_text for chunk {chunk_id}"
                )

            records.append(record)

    if not records:
        raise ValueError(
            f"No chunk records were loaded from {CHUNKS_FILE}"
        )

    chunk_ids = [
        str(record["chunk_id"])
        for record in records
    ]

    # Reject duplicate IDs because metadata and embedding rows must retain a
    # one-to-one mapping throughout retrieval.
    duplicate_ids = {
        chunk_id
        for chunk_id in chunk_ids
        if chunk_ids.count(chunk_id) > 1
    }

    if duplicate_ids:
        preview = sorted(duplicate_ids)[:5]

        raise ValueError(
            f"Duplicate chunk IDs found: {preview}"
        )

    return records


def build_embeddings(
    records: list[dict[str, Any]],
) -> tuple[np.ndarray, SentenceTransformer]:
    """Generate locally normalised embeddings for all strategy chunks."""

    # Embed search_text rather than passage text alone so collection/theme/
    # strategy metadata contributes to semantic retrieval.
    search_texts = [
        str(record["search_text"])
        for record in records
    ]

    print(f"Loading local embedding model: {MODEL_NAME}")
    print("The first run may download the model files.")
    print()

    # Load the fixed sentence-transformer locally on CPU; the first run may
    # populate the local model cache.
    model = SentenceTransformer(
        MODEL_NAME,
        device=DEVICE,
    )

    # Request unit-normalised NumPy vectors directly so cosine similarity can
    # later be implemented as a simple dot product.
    embeddings = model.encode(
        search_texts,
        batch_size=BATCH_SIZE,
        show_progress_bar=True,
        convert_to_numpy=True,
        normalize_embeddings=True,
    )

    # Store vectors as float32 to keep the on-disk index compact and consistent.
    embeddings = np.asarray(
        embeddings,
        dtype=np.float32,
    )

    return embeddings, model


def validate_embeddings(
    embeddings: np.ndarray,
    expected_count: int,
) -> None:
    """Validate embedding count, shape and normalisation."""

    # Validate shape/count/finite values before saving any index artifacts.
    if embeddings.ndim != 2:
        raise ValueError(
            f"Expected a two-dimensional embedding array, "
            f"but received shape {embeddings.shape}"
        )

    if embeddings.shape[0] != expected_count:
        raise ValueError(
            f"Embedding count mismatch: expected {expected_count}, "
            f"received {embeddings.shape[0]}"
        )

    if embeddings.shape[1] == 0:
        raise ValueError(
            "The embedding dimension cannot be zero."
        )

    if not np.isfinite(embeddings).all():
        raise ValueError(
            "The embeddings contain NaN or infinite values."
        )

    # Verify that every vector is approximately unit length, which is required
    # for the later cosine-via-dot-product retrieval calculation.
    vector_norms = np.linalg.norm(
        embeddings,
        axis=1,
    )

    if not np.allclose(
        vector_norms,
        1.0,
        atol=1e-4,
    ):
        raise ValueError(
            "The embeddings were not correctly normalised."
        )


def save_metadata(
    records: list[dict[str, Any]],
) -> None:
    """
    Save metadata in exactly the same order as the embedding rows.

    embedding_position identifies the corresponding row in the
    strategy_embeddings.npy array.
    """

    # Metadata is written in exactly the same order as embedding rows so
    # embedding_position remains a stable row-to-chunk link.
    with METADATA_FILE.open(
        "w",
        encoding="utf-8",
    ) as file:
        for position, record in enumerate(records):
            # Persist the zero-based embedding row position alongside all original
            # chunk metadata used for evidence display and provenance.
            metadata_record = {
                "embedding_position": position,
                **record,
            }

            file.write(
                json.dumps(
                    metadata_record,
                    ensure_ascii=False,
                )
                + "\n"
            )


def save_manifest(
    records: list[dict[str, Any]],
    embeddings: np.ndarray,
    model: SentenceTransformer,
) -> None:
    """Save reproducibility and index-validation information."""

    # Record the model-reported dimension separately from the generated array
    # shape so index inconsistencies can be detected later.
    model_dimension = (
        model.get_sentence_embedding_dimension()
    )

    # Capture model/library versions, corpus hash, dimensions, dtype and
    # similarity assumptions as a reproducibility record for the index.
    manifest = {
        "index_name": "hey_joey_strategy_semantic_index",
        "created_at_utc": datetime.now(
            timezone.utc
        ).isoformat(),
        "model_name": MODEL_NAME,
        "device": DEVICE,
        "sentence_transformers_version": version(
            "sentence-transformers"
        ),
        "numpy_version": np.__version__,
        "source_chunks_file": str(
            CHUNKS_FILE.relative_to(PROJECT_ROOT)
        ),
        "source_chunks_sha256": calculate_sha256(
            CHUNKS_FILE
        ),
        "chunk_count": len(records),
        "embedding_count": int(
            embeddings.shape[0]
        ),
        "embedding_dimension": int(
            embeddings.shape[1]
        ),
        "model_reported_dimension": model_dimension,
        "embedding_dtype": str(
            embeddings.dtype
        ),
        "normalised_embeddings": True,
        "similarity_method": (
            "cosine similarity using dot product "
            "between unit-normalised vectors"
        ),
        "embeddings_file": EMBEDDINGS_FILE.name,
        "metadata_file": METADATA_FILE.name,
    }

    MANIFEST_FILE.write_text(
        json.dumps(
            manifest,
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )


def main() -> None:
    """Build the local Hey Joey strategy embedding index."""

    # Create the index directory before writing embeddings, metadata or manifest.
    INDEX_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    print("\nHEY JOEY LOCAL EMBEDDING INDEX BUILDER")
    print("=" * 60)

    # Load and validate the deterministic chunk corpus before the heavier model
    # encoding step begins.
    records = load_chunks()

    print(f"Chunks loaded: {len(records)}")

    # Generate all semantic vectors in corpus order so metadata alignment is
    # preserved through saving and retrieval.
    embeddings, model = build_embeddings(
        records
    )

    # Refuse to persist an index whose shape, values or normalisation are invalid.
    validate_embeddings(
        embeddings,
        expected_count=len(records),
    )

    # The array contains only numeric values, so pickle is disabled.
    # Disabling pickle keeps loading limited to the expected numeric NumPy data.
    np.save(
        EMBEDDINGS_FILE,
        embeddings,
        allow_pickle=False,
    )

    # Save row-aligned metadata and a separate reproducibility manifest after
    # the numeric embedding array has been written successfully.
    save_metadata(records)
    save_manifest(
        records,
        embeddings,
        model,
    )

    print("\nEmbedding index summary")
    print("-" * 60)
    print(f"Chunks loaded: {len(records)}")
    print(
        f"Embeddings created: "
        f"{embeddings.shape[0]}"
    )
    print(
        f"Embedding dimensions: "
        f"{embeddings.shape[1]}"
    )
    print(
        f"Embedding data type: "
        f"{embeddings.dtype}"
    )
    print("Normalised embeddings: Yes")
    print(f"Embeddings: {EMBEDDINGS_FILE}")
    print(f"Metadata: {METADATA_FILE}")
    print(f"Manifest: {MANIFEST_FILE}")
    print("\nLocal semantic index created successfully.")


# Build the semantic index only when this module is executed directly.
if __name__ == "__main__":
    main()
